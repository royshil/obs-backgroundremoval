TABLE_TEMPLATE = Template("""\
extern constexpr std::array<$type_name, $entry_count> $name{{
$entries
}};""")


def render_table(type_name: str, name: str, entries: list[str]) -> str:
    return TABLE_TEMPLATE.substitute(
        type_name=type_name, name=name, entry_count=len(entries),
        entries="\n".join(f"\t{entry}," for entry in entries),
    )


def render_weight_literals(data: bytes | bytearray) -> str:
    escaped = "".join(f"\\x{byte:02x}" for byte in data)
    return f'"{escaped}"'


def float_literal(value: float) -> str:
    result = f"{value:.9g}"
    if "." not in result and "e" not in result.lower():
        result += ".0"
    return result + "F"


def attrs(node: onnx.NodeProto) -> dict[str, object]:
    return {item.name: onnx.helper.get_attribute_value(item) for item in node.attribute}


def lower_model(model: onnx.ModelProto, fuse_hard_swish: bool = True) -> onnx.ModelProto:
    """Specialize the pinned model and lower it to the DirectML 1.0 operator set."""
    onnx.checker.check_model(model)
    if len(model.graph.input) != 1 or len(model.graph.output) != 1:
        raise RuntimeError("MediaPipe Landscape requires one input and one output")
    input_shape = model.graph.input[0].type.tensor_type.shape
    if [d.dim_value for d in input_shape.dim[1:]] != INPUT_SHAPE[1:]:
        raise RuntimeError("Expected MediaPipe Landscape NCHW RGB input")
    input_shape.dim[0].dim_value = 1
    model = shape_inference.infer_shapes(model, data_prop=True)
    shapes = {
        v.name: [d.dim_value for d in v.type.tensor_type.shape.dim]
        for v in [*model.graph.input, *model.graph.value_info, *model.graph.output]
    }
    if shapes[model.graph.output[0].name] != OUTPUT_SHAPE:
        raise RuntimeError("Expected MediaPipe Landscape single-channel alpha output")

    def constant(name: str, value: np.ndarray) -> str:
        model.graph.initializer.append(numpy_helper.from_array(value, name))
        return name

    lowered = []
    for index, node in enumerate(model.graph.node):
        prefix = f"baseline_dml_{index}"
        if node.op_type == "HardSwish":
            if fuse_hard_swish:
                lowered.extend([
                    onnx.helper.make_node("HardSigmoid", [node.input[0]], [prefix + "_gate"],
                                          alpha=1 / 6, beta=0.5),
                    onnx.helper.make_node("Mul", [node.input[0], prefix + "_gate"], list(node.output)),
                ])
                continue
            three = constant(prefix + "_three", np.full((1, 1, 1, 1), 3, dtype=np.float32))
            zero = constant(prefix + "_zero", np.array(0, dtype=np.float32))
            six = constant(prefix + "_six", np.array(6, dtype=np.float32))
            sixth = constant(prefix + "_sixth", np.full((1, 1, 1, 1), 1 / 6, dtype=np.float32))
            lowered.extend([
                onnx.helper.make_node("Add", [node.input[0], three], [prefix + "_add"]),
                onnx.helper.make_node("Clip", [prefix + "_add", zero, six], [prefix + "_clip"]),
                onnx.helper.make_node("Mul", [sixth, prefix + "_clip"], [prefix + "_scale"]),
                onnx.helper.make_node("Mul", [node.input[0], prefix + "_scale"], list(node.output)),
            ])
        elif node.op_type == "ReduceMean":
            attribute = attrs(node)
            if list(attribute.get("axes", [])) != [2, 3] or attribute.get("keepdims", 1) != 1:
                raise RuntimeError("Expected spatial ReduceMean with keepdims")
            lowered.append(onnx.helper.make_node(
                "AveragePool", list(node.input), list(node.output),
                kernel_shape=shapes[node.input[0]][2:], strides=[1, 1],
            ))
        elif node.op_type == "Resize":
            attribute = attrs(node)
            source, destination = shapes[node.input[0]], shapes[node.output[0]]
            if (attribute.get("mode") != b"linear"
                    or attribute.get("coordinate_transformation_mode") != b"half_pixel"
                    or source[:2] != destination[:2]
                    or any(d <= 0 or d % s for s, d in zip(source[2:], destination[2:]))):
                raise RuntimeError("Expected integer half-pixel linear spatial upsampling")
            sizes = constant(prefix + "_sizes", np.array(destination, dtype=np.int64))
            replacement = onnx.NodeProto()
            replacement.CopyFrom(node)
            del replacement.input[:]
            replacement.input.extend([node.input[0], "", "", sizes])
            lowered.append(replacement)
        else:
            lowered.append(node)

    # Resize sizes are now static, so the original Shape/Slice/Concat chains are dead.
    needed = {model.graph.output[0].name}
    live = []
    for node in reversed(lowered):
        if needed.intersection(node.output):
            live.append(node)
            needed.update(name for name in node.input if name)
    del model.graph.node[:]
    model.graph.node.extend(reversed(live))
    del model.graph.value_info[:]
    model = shape_inference.infer_shapes(model, data_prop=True)
    onnx.checker.check_model(model)
    return model


def dimensions(values: list[int]) -> str:
    return "{" + ", ".join(f"{value}u" for value in values) + "}"


DATA_TYPES = {
    onnx.TensorProto.FLOAT: "Float32", onnx.TensorProto.FLOAT16: "Float16",
    onnx.TensorProto.UINT32: "UInt32", onnx.TensorProto.UINT16: "UInt16",
    onnx.TensorProto.UINT8: "UInt8", onnx.TensorProto.INT32: "Int32",
    onnx.TensorProto.INT16: "Int16", onnx.TensorProto.INT8: "Int8",
    onnx.TensorProto.DOUBLE: "Float64", onnx.TensorProto.UINT64: "UInt64",
    onnx.TensorProto.INT64: "Int64",
}
GROUPS = {
    "AveragePool2d": "Onnx11Node", "BiasedConv2d": "Onnx11Node",
    "BiasedConvTranspose2d": "Onnx11Node", "DepthToSpace": "Onnx11Node",
    "MPLD10DepthwiseConv2dRelu": "FusedNode", "BiasedConv2dRelu": "FusedNode", "HardSwishGate": "FusedNode",
    "ClipFloat32": "Onnx13Node", "Resize": "Onnx13Node", "Sigmoid": "Onnx13Node",
    "Add": "Onnx14Node", "Mul": "Onnx14Node", "Relu": "Onnx14Node",
}


def data_type(element_type: int) -> str:
    if element_type not in DATA_TYPES:
        raise RuntimeError(f"unsupported tensor data type: {element_type}")
    return "dt" + DATA_TYPES[element_type]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--offline", action="store_true", help="Use the cached pinned model only")
    parser.add_argument("--float32", action="store_true", help="Compatibility option: execution and embedded weights are always FP32")
    parser.add_argument("--no-mpld10-depthwise-conv", action="store_true", help="Use native DML for the Node 230 depthwise Conv+ReLU baseline")
    parser.add_argument("--no-pointwise-projection", action="store_true", help="Keep backward DML ConvTranspose instead of the fixed pointwise graph conversion")
    parser.add_argument("--no-fuse-hard-swish", action="store_true", help="Keep four DML operations per HardSwish for benchmarking")
    parser.add_argument("--no-fuse-conv-relu", action="store_true", help="Generate the unfused performance baseline")
    parser.add_argument("--uav-placement", choices=["first-consumer", "early-batched"],
                        default="first-consumer", help="Place output barriers at first use or an earlier existing boundary")
    parser.add_argument("source", type=pathlib.Path)
    args = parser.parse_args()

    model_path = hf_hub_download(
        repo_id=MODEL_REPOSITORY, revision=MODEL_REVISION, filename=MODEL_FILENAME,
        local_files_only=args.offline,
    )
    if hashlib.sha256(pathlib.Path(model_path).read_bytes()).hexdigest() != MODEL_SHA256:
        raise RuntimeError("The pinned MediaPipe Landscape model SHA-256 does not match")
    original_model = onnx.load(model_path)
    original_nodes = {tuple(node.output): (index, node.op_type, node.name)
                      for index, node in enumerate(original_model.graph.node)}
    model = lower_model(original_model, not args.no_fuse_hard_swish)
    shapes = {
        value.name: [int(dimension.dim_value) for dimension in value.type.tensor_type.shape.dim]
        for value in [*model.graph.input, *model.graph.value_info, *model.graph.output]
    }
    initializers = {item.name: item for item in model.graph.initializer}
    nodes = list(model.graph.node)
    projection_origins = {}
    if not args.no_pointwise_projection:
        converted = []
        for node in nodes:
            attribute = attrs(node)
            if (node.op_type == "ConvTranspose" and not node.domain and len(node.input) == 3
                    and shapes[node.input[0]] == [1, 16, 72, 128]
                    and list(initializers[node.input[1]].dims) == [16, 1, 2, 2]
                    and list(initializers[node.input[2]].dims) == [1]
                    and shapes[node.output[0]] == [1, 1, 144, 256]
                    and list(attribute.get("strides", [1, 1])) == [2, 2]
                    and list(attribute.get("dilations", [1, 1])) == [1, 1]
                    and list(attribute.get("pads", [0, 0, 0, 0])) == [0, 0, 0, 0]
                    and int(attribute.get("group", 1)) == 1
                    and list(attribute.get("output_padding", [0, 0])) == [0, 0]
                    and attribute.get("auto_pad", b"NOTSET") == b"NOTSET"
                    and list(attribute.get("output_shape", [144, 256])) == [144, 256]):
                # W'[dy*2+dx,c,0,0] = W[c,0,dy,dx]. Keep shared originals intact.
                stem = node.output[0] + "__pointwise"
                weight_name, bias_name = stem + "_weight", stem + "_bias"
                if any(name in shapes or name in initializers for name in (stem, weight_name, bias_name)):
                    raise RuntimeError("pointwise projection name collision")
                weights = numpy_helper.to_array(initializers[node.input[1]])
                bias = numpy_helper.to_array(initializers[node.input[2]])
                initializers[weight_name] = numpy_helper.from_array(
                    weights[:, 0].reshape(16, 4).T.copy().reshape(4, 16, 1, 1), weight_name)
                initializers[bias_name] = numpy_helper.from_array(np.repeat(bias, 4), bias_name)
                shapes[stem] = [1, 4, 72, 128]
                projection_origins[stem] = projection_origins[node.output[0]] = original_nodes[tuple(node.output)]
                converted.append(onnx.helper.make_node("Conv", [node.input[0], weight_name, bias_name],
                    [stem], name=stem, kernel_shape=[1, 1]))
                converted.append(onnx.helper.make_node("DepthToSpace", [stem], list(node.output),
                    name=stem + "_shuffle", blocksize=2, mode="DCR"))
            else:
                converted.append(node)
        nodes = converted
    ignored_inputs = {"Clip": {1, 2}, "Resize": {1, 2, 3}}
    allowed = {"HardSigmoid", "Add", "Mul", "Relu", "Clip", "Resize", "Sigmoid", "AveragePool", "Conv", "ConvTranspose", "DepthToSpace"}
    for index, node in enumerate(nodes):
        if node.op_type not in allowed:
            raise RuntimeError(f"node {index}: operator {node.op_type} is outside the pinned Landscape variants")
    types = {
        value.name: data_type(value.type.tensor_type.elem_type)
        for value in [*model.graph.input, *model.graph.value_info, *model.graph.output]
    }
    for value in projection_origins:
        types[value] = "dtFloat32"
    used_initializers = {
        name
        for node in nodes
        for index, name in enumerate(node.input)
        if name in initializers and index not in ignored_inputs.get(node.op_type, set())
    }

    def shape_fields(values: list[int]) -> str:
        if not 1 <= len(values) <= 4 or any(not 0 < value < 2**31 for value in values):
            raise RuntimeError(f"unsupported shape: {values}")
        return f"{len(values)}, {dimensions(values)}"

    spec_entries = []
    spec_indices = {}
    runtime_inputs = [value for value in model.graph.input if value.name not in initializers]
    for value in runtime_inputs:
        spec_indices[value.name] = len(spec_entries)
        spec_entries.append(f"{{kRuntimeInput, {types[value.name]}, {shape_fields(shapes[value.name])}}}")
    weight_data = bytearray()
    for name, initializer in initializers.items():
        if name not in used_initializers:
            continue
        array = numpy_helper.to_array(initializer)
        dtype = data_type(initializer.data_type)
        types[name] = dtype
        if initializer.data_type != onnx.TensorProto.FLOAT:
            raise RuntimeError(f"Landscape execution requires FP32 weights: {name}")
        if not np.isfinite(array).all():
            raise RuntimeError(f"Weight contains nonfinite FP32 values: {name}")
        offset = len(weight_data)
        weight_data.extend(array.astype("<f4", copy=False).tobytes(order="C"))
        spec_indices[name] = len(spec_entries)
        spec_entries.append(f"{{{offset}LL, {dtype}, {shape_fields(list(initializer.dims) or [1])}}}")
    if len(weight_data) >= 2**63:
        raise RuntimeError("weight data exceeds the BaselineDml signed 64-bit offset range")
    if not spec_entries or len(spec_entries) > 2**31 - 1:
        raise RuntimeError("input specification count is outside the int32 range")

    # Model-specific Conv -> Relu lowering; never change a shared/raw Conv output.
    consumers = {}
    for index, node in enumerate(nodes):
        for name in node.input:
            consumers.setdefault(name, []).append(index)
    graph_outputs = {value.name for value in model.graph.output}
    fused_relu = {}
    for index, node in enumerate(nodes):
        if node.op_type != "Conv" or len(node.output) != 1:
            continue
        value = node.output[0]
        uses = consumers.get(value, [])
        if value in graph_outputs or len(uses) != 1:
            continue
        relu_index = uses[0]
        relu = nodes[relu_index]
        if (relu_index > index and relu.op_type == "Relu" and not relu.domain
                and list(relu.input) == [value] and len(relu.output) == 1 and not relu.attribute
                and shapes[value] == shapes[relu.output[0]]
                and types[value] == types[relu.output[0]]):
            fused_relu[index] = relu_index
    if args.no_fuse_conv_relu:
        fused_relu.clear()
    skipped_relu = set(fused_relu.values())

    value_sources = {}
    node_entries = []
    barrier_entries = []
    node_types = []
    pending_writes = []
    for value in runtime_inputs:
        value_sources[value.name] = len(node_entries)
        node_entries.append(f"InputItem{{{types[value.name]}, {spec_indices[value.name]}}}")
        node_types.append(types[value.name])
        pending_writes.append(False)
        barrier_entries.append([])

    def source(name: str) -> str:
        if name not in value_sources:
            if name not in spec_indices:
                raise RuntimeError(f"input {name} is not a constant or preceding node")
            node_entries.append(f"InputItem{{{types[name]}, {spec_indices[name]}}}")
            node_types.append(types[name])
            pending_writes.append(False)
            barrier_entries.append([])
            value_sources[name] = len(node_entries) - 1
        return str(value_sources[name])

    for node_index, node in enumerate(nodes):
        if node_index in skipped_relu:
            continue
        if len(node.output) != 1:
            raise RuntimeError(f"node {node_index} has {len(node.output)} outputs")
        attribute = attrs(node)
        output_shape = shapes[node.output[0]]
        output = shape_fields(output_shape)
        inputs = [source(name) for index, name in enumerate(node.input)
                  if name and index not in ignored_inputs.get(node.op_type, set())]
        if node.op_type in {"Add", "Mul"}:
            entry = f"{node.op_type}{{{inputs[0]}, {inputs[1]}, {output}}}"
        elif node.op_type == "HardSigmoid":
            entry = f"HardSwishGate{{{inputs[0]}, {output}}}"
        elif node.op_type == "Clip":
            minimum = float(numpy_helper.to_array(initializers[node.input[1]]).reshape(-1)[0])
            maximum = float(numpy_helper.to_array(initializers[node.input[2]]).reshape(-1)[0])
            entry = f"ClipFloat32{{{inputs[0]}, {output}, {float_literal(minimum)}, {float_literal(maximum)}}}"
        elif node.op_type in {"Relu", "Sigmoid"}:
            entry = f"{node.op_type}{{{inputs[0]}, {output}}}"
        elif node.op_type in {"Conv", "ConvTranspose"}:
            strides = list(attribute.get("strides", [1, 1]))
            dilations = list(attribute.get("dilations", [1, 1]))
            pads = list(attribute.get("pads", [0, 0, 0, 0]))
            filter_shape = list(initializers[node.input[1]].dims)
            if (len(shapes[node.input[0]]) != 4 or len(filter_shape) != 4
                    or len(output_shape) != 4 or len(strides) != 2
                    or len(dilations) != 2 or len(pads) != 4):
                raise RuntimeError(f"{node.op_type} requires two spatial dimensions")
            if len(inputs) != 3:
                raise RuntimeError(f"node {node_index}: unbiased {node.op_type} is outside the pinned Landscape variants")
            kind = "BiasedConv2dRelu" if node_index in fused_relu else "Biased" + node.op_type + "2d"
            if (not args.no_mpld10_depthwise_conv and kind == "BiasedConv2dRelu"
                    and shapes[node.input[0]] == [1, 16, 72, 128]
                    and output_shape == [1, 16, 72, 128] and filter_shape == [16, 1, 3, 3]
                    and list(initializers[node.input[2]].dims) == [16]
                    and strides == [1, 1] and dilations == [1, 1] and pads == [1, 1, 1, 1]
                    and int(attribute.get("group", 1)) == 16
                    and attribute.get("auto_pad", b"NOTSET") == b"NOTSET"
                    and types[node.output[0]] == "dtFloat32"):
                kind = "MPLD10DepthwiseConv2dRelu"
            connections = ", ".join(inputs)
            group = int(attribute.get("group", 1))
            entry = (f"{kind}{{{connections}, "
                     f"{dimensions(strides)}, {dimensions(dilations)}, "
                     f"{dimensions(pads[:2])}, {dimensions(pads[2:])}, {group}u, {dimensions(output_shape)}}}")
        elif node.op_type == "DepthToSpace":
            if attribute.get("mode", b"DCR") != b"DCR":
                raise RuntimeError("DepthToSpace requires DCR order")
            entry = f"DepthToSpace{{{inputs[0]}, {int(attribute['blocksize'])}u, {dimensions(output_shape)}}}"
        elif node.op_type == "AveragePool":
            kernel = list(attribute["kernel_shape"])
            strides = list(attribute.get("strides", kernel))
            pads = list(attribute.get("pads", [0, 0, 0, 0]))
            if (len(shapes[node.input[0]]) != 4 or len(output_shape) != 4
                    or len(kernel) != 2 or len(strides) != 2 or len(pads) != 4):
                raise RuntimeError("AveragePool requires two spatial dimensions")
            entry = (f"AveragePool2d{{{inputs[0]}, {dimensions(strides)}, "
                     f"{dimensions(kernel)}, {dimensions(pads[:2])}, {dimensions(pads[2:])}, {dimensions(output_shape)}}}")
        elif node.op_type == "Resize":
            input_shape = shapes[node.input[0]]
            if len(input_shape) != 4 or len(output_shape) != 4:
                raise RuntimeError("Resize requires rank-4 input and output")
            entry = (f"Resize{{{inputs[0]}, {len(output_shape)}, "
                     f"{output_shape[-2] // input_shape[-2]}u, {output_shape[-1] // input_shape[-1]}u, {dimensions(output_shape)}}}")
        else:
            raise RuntimeError(f"unsupported node {node_index}: {node.op_type}")
        if entry.startswith(("MPLD10DepthwiseConv2dRelu{",)):
            entry = entry.split("{", 1)[0] + "{" + connections + "}"
        kind = entry.split("{", 1)[0]
        dtype = types[node.output[0]]
        barriers = []
        # Inputs/weights are ordered by transfer/initialization. An operator's
        # dedicated output needs a UAV barrier at its first consumer only.
        # A repeated input is synchronized once, in input order.
        for value in inputs:
            producer = int(value)
            if not 0 <= producer < len(node_entries):
                raise RuntimeError(f"node {node_index}: input must reference a preceding node")
            if node_types[producer] != dtype:
                raise RuntimeError(f"node {node_index}: input/output data type mismatch")
            if pending_writes[producer]:
                barriers.append(producer)
            pending_writes[producer] = False
        arguments = entry.split("{", 1)[1][:-1]
        if kind == "ClipFloat32":
            if dtype != "dtFloat32":
                raise RuntimeError(f"node {node_index}: ClipFloat32 requires Float32")
            entry = f"{GROUPS[kind]}{{{kind}{{{arguments}}}}}"
        else:
            entry = f"{GROUPS[kind]}{{{kind}{{{dtype}, {arguments}}}}}"
        barrier_entries.append(barriers)
        node_types.append(dtype)
        pending_writes.append(True)
        if node.output[0] in projection_origins:
            origin = projection_origins[node.output[0]]
            entry = (f"// Original ONNX #{origin[0]} ConvTranspose {json.dumps(origin[2])}: "
                     f"fixed graph conversion, {kind}; Sigmoid stays separate.\n\t" + entry)
        if node.op_type == "HardSigmoid":
            original_index = int(node.output[0].split("_")[2])
            original = original_model.graph.node[original_index]
            entry = (f"// Original ONNX #{original_index} HardSwish {json.dumps(original.name)}: "
                     "Add -> Clip -> scalar Mul gate; following Mul completes HardSwish.\n\t" + entry)
        if node_index in fused_relu:
            relu = nodes[fused_relu[node_index]]
            conv_origin = original_nodes[tuple(node.output)]
            relu_origin = original_nodes[tuple(relu.output)]
            entry = (f"// Original ONNX #{conv_origin[0]} Conv {json.dumps(conv_origin[2])} -> "
                     f"#{relu_origin[0]} Relu {json.dumps(relu_origin[2])}\n\t" + entry)
            value_sources[relu.output[0]] = len(node_entries)
        node_entries.append(entry)
        value_sources[node.output[0]] = len(node_entries) - 1

    model_spec_count = len(spec_entries)
    model_node_count = len(node_entries)
    output_index = value_sources[model.graph.output[0].name]
    # Fixed model-resolution postprocessing is part of the same immutable graph.
    spec_entries.append("{kRuntimeInput, dtFloat32, 4, {1, 1, 1, 1}}")
    node_entries.extend([
        f"InputItem{{dtFloat32, {model_spec_count}}}",
        f"FusedNode{{MPLD10BinarizeFloat32{{{output_index}, {model_node_count}}}}}",
        f"Onnx11Node{{AveragePool2d{{dtFloat32, {model_node_count + 1}, "
        "{1, 1}, {5, 5}, {2, 2}, {2, 2}, {1, 1, 144, 256}}}",
    ])
    barrier_entries.extend([[], [output_index], [model_node_count + 1]])

    if len(barrier_entries) != len(node_entries):
        raise RuntimeError("UAV barrier table does not match Node count")
    if len(node_entries) > 2**31 - 1:
        raise RuntimeError("node indices exceed the int32 range")
    # Dedicated outputs are written once. Each first-use barrier can move to
    # any boundary after its producer and no later than that first use.
    # Keep the baseline boundaries so early batching cannot add API calls.
    baseline_barriers = [row.copy() for row in barrier_entries]
    if args.uav_placement == "early-batched":
        boundaries = [index for index, row in enumerate(baseline_barriers) if row]
        barrier_entries = [[] for _ in node_entries]
        for first_use, row in enumerate(baseline_barriers):
            for producer in row:
                boundary = next(index for index in boundaries
                                if producer < index <= first_use)
                barrier_entries[boundary].append(producer)
    # Check that every baseline dependency still has exactly one barrier in
    # its legal interval. No read-after-write dependency may be removed.
    expected = {producer: first_use for first_use, row in enumerate(baseline_barriers) for producer in row}
    actual = {}
    for boundary, row in enumerate(barrier_entries):
        for producer in row:
            if producer in actual or not producer < boundary <= expected[producer]:
                raise RuntimeError("invalid UAV barrier placement")
            actual[producer] = boundary
    if actual.keys() != expected.keys():
        raise RuntimeError("missing UAV barrier dependency")
    print(json.dumps({"uav_placement": args.uav_placement,
                      "barriers": len(actual),
                      "boundaries": sum(bool(row) for row in barrier_entries),
                      "moved": sum(actual[producer] != first_use for producer, first_use in expected.items())}))
    barrier_entries = [f"{{{boundary}, {producer}}}"
                       for boundary, row in enumerate(barrier_entries) for producer in row]
    source_code = CPP_TEMPLATE.substitute(
        model_repository=MODEL_REPOSITORY,
        model_revision=MODEL_REVISION,
        model_filename=MODEL_FILENAME,
        input_specs=render_table("InputSpecItem", "inputSpecs", spec_entries),
        graph_nodes=render_table("Node", "graphNodes", node_entries),
        uav_barriers=render_table("std::pair<std::int32_t, std::int32_t>", "uavBarriers", barrier_entries),
        weight_literals=render_weight_literals(weight_data),
        weight_bytes=len(weight_data),
    )
    args.source.parent.mkdir(parents=True, exist_ok=True)
    with args.source.open("w", encoding="utf-8", newline="\n") as stream:
        stream.write(source_code)
    subprocess.run(["clang-format", "-i", str(args.source)], check=True)


